%% 燃料電池理論效率隨溫度變化曲線
T = [298.15; 300; 373.15; 400; 500; 600; 700; 800; 900; 1000; 1100; 1200; 1300];
H = [-285.83; -285.771; -283.874; -242.846; -243.826; -244.758; -245.632; ...
     -246.443; -247.185; -247.857; -248.46; -248.997; -249.473];
S = [-163.302; -163.106; -157.324; -47.238; -49.428; -51.128; -52.476; ...
     -53.561; -54.435; -55.143; -55.720; -56.188; -56.569];

% 計算 G 與 效率 n
G = H - (T .* S) / 1000;
n_fc = G ./ H;

% 繪圖
figure('Color', [1, 1, 1], 'Position', [200, 200, 600, 450]);
plot(T, n_fc, 'r-s', 'LineWidth', 2, 'MarkerSize', 6, 'MarkerFaceColor', 'r');

% 裝飾圖表
grid on;
xlabel('溫度 T (K)', 'FontSize', 12);
ylabel('燃料电池理论效率 \eta = \DeltaG / \DeltaH', 'FontSize', 12);
title('常压下燃料电池的可逆效率曲线', 'FontSize', 14);


% 設置坐標軸
ylim([0.6, 1.0]);
set(gca, 'Box', 'on', 'LineWidth', 1.2);